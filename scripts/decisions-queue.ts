#!/usr/bin/env bun
/**
 * Self-clearing decisions queue (Phase 2A, spec §5.5).
 *
 * Entries are PREDICATES over existing artifacts, re-evaluated at generation
 * time: the operator resolves an item by fixing the underlying thing (add the
 * address, un-quarantine the source, correct the event) and the entry
 * disappears on the next run. No state to maintain, nothing to mark done —
 * except operator one-timers, whose done-flags live in the registry below.
 *
 * Output: docs/DECISIONS-QUEUE.md — COMPUTED; every count real.
 * Runs in daily-automated.sh right after venue-address-autofix.
 */
import { Database } from 'bun:sqlite';
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join } from 'path';
import { loadQuarantine } from '../src/utils/quarantine';
import type { AddressProposal } from './venue-address-autofix';

const ROOT = join(import.meta.dir, '..');
const OUT_PATH = join(ROOT, 'docs', 'DECISIONS-QUEUE.md');

// Operator one-timers: flip done:true when completed (this file is the
// registry — a one-liner edit, reviewed like any code change).
const OPERATOR_ONE_TIMERS: OperatorItem[] = [
  { id: 'pmset-wake', summary: 'Run the two `sudo pmset` commands (docs/LAUNCHD-SETUP.md §Machine wake schedule) — the Aug 13-27 machine-asleep gap was the root of the 18-day outage', done: false },
  { id: 'github-app', summary: 'Install the Claude GitHub App so the cloud watcher can read the repo and file issues (PHASE3.md §5 cloud-track step 1)', done: false },
  { id: 'circus-venue-city', summary: 'Verify "Circus Entertainment Hub" (whitelist says Gazi; S224 found it during the Eightball/Block 33 Thessaloniki sweep — confirm it is genuinely Athens or remove it)', done: false },
];

export interface OperatorItem {
  id: string;
  summary: string;
  done: boolean;
}

export interface DateProposal {
  event_id: string;
  title: string;
  current_start: string;
  proposed_date: string | null;
  concern: string | null;
}

export interface QueueInputs {
  addressProposals: AddressProposal[];
  /** venues that HAVE an address in config/athens-venues.json (clears proposals) */
  configuredVenues: Set<string>;
  quarantined: Record<string, { since: string; reason: string }>;
  upcomingConcerns: Array<{ event_id: string; concern_type: string; concern_text: string | null }>;
  /** post-save validator rollover proposals — pre-filtered by the gatherer to
   *  events that still carry the flagged start_date (self-clearing) */
  dateProposals?: DateProposal[];
  operatorOneTimers: OperatorItem[];
}

export function renderQueue(inputs: QueueInputs): string {
  const lines: string[] = [];
  lines.push('<!-- COMPUTED by scripts/decisions-queue.ts — do not edit; fix the underlying thing and regenerate -->');
  lines.push('# Decisions Queue');
  lines.push('');

  const pendingAddresses = inputs.addressProposals.filter((p) => !inputs.configuredVenues.has(p.venue));
  const quarantineEntries = Object.entries(inputs.quarantined);
  const oneTimers = inputs.operatorOneTimers.filter((o) => !o.done);
  const dateProposals = inputs.dateProposals ?? [];

  const total = pendingAddresses.length + quarantineEntries.length + inputs.upcomingConcerns.length + oneTimers.length + dateProposals.length;
  lines.push(`**Pending: ${total}** (regenerated by the daily pipeline; resolve by fixing the thing, not by editing this file)`);
  lines.push('');

  if (total === 0) {
    lines.push('Nothing pending. 🎉');
    lines.push('');
    return lines.join('\n');
  }

  if (pendingAddresses.length > 0) {
    lines.push(`## Venue addresses needed (${pendingAddresses.length}) — each is a future F2b build-stop`);
    lines.push('');
    lines.push('Add the address to `config/athens-venues.json` (verify before trusting a geocode — same-name venues exist in other cities).');
    lines.push('');
    for (const p of pendingAddresses) {
      const proposal = p.proposedAddress
        ? `geocoded **${p.proposedAddress}** (${p.geocodeConfidence}${p.locationType ? ', ' + p.locationType : ''})`
        : 'geocoder found nothing — manual research needed';
      lines.push(`- **${p.venue}** — ${proposal} _(since ${p.since})_`);
    }
    lines.push('');
  }

  if (quarantineEntries.length > 0) {
    lines.push(`## Quarantined sources (${quarantineEntries.length})`);
    lines.push('');
    for (const [id, q] of quarantineEntries) {
      lines.push(`- **${id}** since ${q.since}: ${q.reason} → to un-quarantine, remove the entry from \`config/quarantined-sources.json\``);
    }
    lines.push('');
  }

  if (dateProposals.length > 0) {
    lines.push(`## Proposed date corrections (${dateProposals.length}) — likely rollover artifacts, never auto-applied`);
    lines.push('');
    for (const p of dateProposals) {
      lines.push(
        `- \`${p.event_id}\` **${p.title}** — start ${p.current_start} looks rolled; ${p.proposed_date ? `proposed **${p.proposed_date}** (from concern text)` : 'no parseable date in concern — verify at source'}`,
      );
    }
    lines.push('');
  }

  if (inputs.upcomingConcerns.length > 0) {
    lines.push(`## Venue concerns on upcoming events (${inputs.upcomingConcerns.length})`);
    lines.push('');
    for (const c of inputs.upcomingConcerns) {
      lines.push(`- \`${c.event_id}\` [${c.concern_type}] ${c.concern_text ?? ''}`);
    }
    lines.push('');
  }

  if (oneTimers.length > 0) {
    lines.push(`## Operator one-timers (${oneTimers.length})`);
    lines.push('');
    for (const o of oneTimers) {
      lines.push(`- ${o.summary} _(mark done in scripts/decisions-queue.ts OPERATOR_ONE_TIMERS when complete)_`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

if (import.meta.main) {
  const proposalsPath = join(ROOT, 'data', 'venue-address-proposals.json');
  const addressProposals: AddressProposal[] = existsSync(proposalsPath)
    ? (JSON.parse(readFileSync(proposalsPath, 'utf8')) as AddressProposal[])
    : [];

  // Venues with a non-empty address in the curated config clear their proposals.
  const configuredVenues = new Set<string>();
  try {
    const cfg = JSON.parse(readFileSync(join(ROOT, 'config', 'athens-venues.json'), 'utf8')) as {
      venues?: Array<{ canonical_name?: string; address?: string; streetAddress?: string }>;
    };
    for (const v of cfg.venues ?? []) {
      const addr = v.address ?? v.streetAddress ?? '';
      if (v.canonical_name && addr.trim() !== '') configuredVenues.add(v.canonical_name);
    }
  } catch {
    // unreadable config → clear nothing (fail toward showing entries)
  }

  const quarantined = loadQuarantine(join(ROOT, 'config', 'quarantined-sources.json')).sources;

  let upcomingConcerns: QueueInputs['upcomingConcerns'] = [];
  try {
    const db = new Database(join(ROOT, 'data', 'events.db'), { readonly: true });
    upcomingConcerns = db
      .query(
        `SELECT c.event_id, c.concern_type, c.concern_text
         FROM event_concerns c JOIN events e ON e.id = c.event_id
         WHERE c.concern_type IN ('venue-mismatch-or-unknown', 'venue-change-suspected')
           AND e.merged_into IS NULL
           AND COALESCE(CASE WHEN e.type='exhibition' THEN e.end_date ELSE NULL END, e.start_date) >= date('now')
         ORDER BY c.created_at DESC LIMIT 50`,
      )
      .all() as QueueInputs['upcomingConcerns'];
    db.close();
  } catch {
    // DB unavailable → render without concerns rather than failing the pipeline
  }

  // Validator date proposals: self-clearing — only while the event still
  // carries the flagged start_date and is not merged away.
  let dateProposals: DateProposal[] = [];
  try {
    const raw = JSON.parse(readFileSync(join(ROOT, 'data', 'validator-proposals.json'), 'utf8')) as DateProposal[];
    const db = new Database(join(ROOT, 'data', 'events.db'), { readonly: true });
    const still = db.prepare(`SELECT 1 FROM events WHERE id = ? AND start_date = ? AND merged_into IS NULL`);
    dateProposals = raw.filter((p) => still.get(p.event_id, p.current_start));
    db.close();
  } catch {
    // no proposals file yet, or DB unavailable → section omitted
  }

  const md = renderQueue({ addressProposals, configuredVenues, quarantined, upcomingConcerns, dateProposals, operatorOneTimers: OPERATOR_ONE_TIMERS });
  writeFileSync(OUT_PATH, md);
  console.log(`[decisions-queue] wrote ${OUT_PATH}`);
}
