/**
 * Writes src/ui/events-html.ts from src/ui/events.html, so the Netlify
 * function and the Worker import the view as an ordinary module. Run after
 * every edit to the HTML; test/ui-module.test.ts fails until you do.
 *
 *   bun run build:ui
 */
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const src = join(import.meta.dir, '..', 'src', 'ui', 'events.html');
const out = join(import.meta.dir, '..', 'src', 'ui', 'events-html.ts');

let html: string;
try {
  html = readFileSync(src, 'utf8');
} catch (err) {
  console.error(`build-ui: FAILED — could not read ${src} (${(err as Error).message})\n  next: run from mcp/ in a full checkout`);
  process.exit(1);
}
writeFileSync(out, `// GENERATED by scripts/build-ui.ts from events.html. Edit the HTML, then run \`bun run build:ui\`.\nexport const EVENTS_HTML = ${JSON.stringify(html)};\n`);
console.log(`build-ui: wrote ${out} (${html.length} characters)`);
